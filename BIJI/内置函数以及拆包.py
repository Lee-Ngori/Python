#内置函数
import builtins
print(dir(builtins))
#内置函数是Python内置的函数，可以直接使用，无需导入模块

#一些内置函数
#abs() 取绝对值
print(abs(-10))
#max() 取最大值
print(max(1,2,3,4))
#list() 将其他数据类型转换为列表
print(list('Hello')) #将字符串转换为列表，每个字符作为列表的一个元素,用中括号进行包围
#str() 将其他数据类型转换为字符串
print(str(123)) #将整数转换为字符串
#tuple() 将其他数据类型转换为元组
print(tuple([1,2,3])) #将列表转换为元组
#set() 将其他数据类型转换为集合
print(set([1,2,3,3])) #将列表转换为集合，集合中不允许重复元素，所以重复的3只保留一个
#sum () 计算可迭代对象的元素之和
print(sum([1,2,3,4])) #计算列表中元素的和

#可迭代对象：可以使用for循环进行迭代的对象，如列表、元组、字符串等